#!/usr/bin/env node
// @file Builds gas-app/Engines.gs from the pure ESM engines in src/integration/*.js so the
// server-side (.gs) code runs the exact logic the node tests cover — no hand-copied logic.
//
// Usage: node tools/build-gas-engines.js [--check]
//   (default) write gas-app/Engines.gs
//   --check   exit 1 if the committed Engines.gs differs from a fresh build (pre-commit/CI gate)
//
// Rules enforced (fail loud, per no-silent-failures.md):
//   - modules may only import from sibling ./*.js files (no bare/npm/parent imports)
//   - no two modules may declare the same top-level name (they share one IIFE scope)
//   - every `export` becomes a member of the single global namespace `DPEngines`
//     (gas-namespace-iife.md: one deliberate global instead of dozens)

import * as acorn from 'acorn';
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const srcDir = path.join(root, 'src', 'integration');
const outFile = path.join(root, 'gas-app', 'Engines.gs');
const NAMESPACE = 'DPEngines';

function moduleOrder(files) {
  // contracts first (everything depends on it), then alphabetical => deterministic output.
  return files.slice().sort((a, b) => {
    if (a === 'contracts.js') return -1;
    if (b === 'contracts.js') return 1;
    return a.localeCompare(b);
  });
}

function declaredNames(node) {
  if (node.type === 'FunctionDeclaration' || node.type === 'ClassDeclaration') return [node.id.name];
  if (node.type === 'VariableDeclaration') {
    return node.declarations.flatMap((d) => {
      if (d.id.type !== 'Identifier') {
        throw new Error('Destructured top-level declarations are not supported in engines');
      }
      return [d.id.name];
    });
  }
  return [];
}

export function buildEngines() {
  const files = moduleOrder(fs.readdirSync(srcDir).filter((f) => f.endsWith('.js')));
  if (files.length === 0) throw new Error(`No engines found in ${srcDir}`);
  const seen = new Map();
  const exported = [];
  const chunks = [];

  for (const file of files) {
    const text = fs.readFileSync(path.join(srcDir, file), 'utf8');
    const ast = acorn.parse(text, { ecmaVersion: 2022, sourceType: 'module', locations: true });
    const edits = []; // {start,end,replacement}
    for (const node of ast.body) {
      if (node.type === 'ImportDeclaration') {
        if (!/^\.\/[\w-]+\.js$/.test(node.source.value)) {
          throw new Error(`${file}: only sibling './x.js' imports are allowed, got '${node.source.value}'`);
        }
        edits.push({ start: node.start, end: node.end, replacement: '' });
        continue;
      }
      if (node.type === 'ExportDefaultDeclaration' || node.type === 'ExportAllDeclaration') {
        throw new Error(`${file}: default/star exports are not supported (use named exports)`);
      }
      let decl = node;
      if (node.type === 'ExportNamedDeclaration') {
        if (!node.declaration) throw new Error(`${file}: 'export { ... }' lists are not supported`);
        decl = node.declaration;
        edits.push({ start: node.start, end: decl.start, replacement: '' });
        for (const n of declaredNames(decl)) exported.push(n);
      }
      for (const n of declaredNames(decl)) {
        if (seen.has(n)) throw new Error(`Duplicate top-level name '${n}' in ${file} and ${seen.get(n)}`);
        seen.set(n, file);
      }
    }
    let out = text;
    for (const e of edits.sort((a, b) => b.start - a.start)) {
      out = out.slice(0, e.start) + e.replacement + out.slice(e.end);
    }
    chunks.push(`// ---- ${file} ----\n${out.trim()}\n`);
  }

  const exportLines = exported.map((n) => `  ${n}: ${n}`).join(',\n');
  return `/**
 * @file Engines.gs
 * @description GENERATED by tools/build-gas-engines.js from src/integration/*.js. DO NOT EDIT BY HAND.
 * Pure Gmail/Calendar/Tasks/Notes hub logic shared with the node unit tests. One IIFE; the only
 * global it creates is \`${NAMESPACE}\` (see .agents/rules/gas-namespace-iife.md). Not reachable via
 * google.script.run: only other .gs files read ${NAMESPACE}.
 */
(function(global) {

${chunks.join('\n')}
// used by other .gs files (Config/Queue/Repository wrappers); not a google.script.run surface
global.${NAMESPACE} = Object.freeze({
${exportLines}
});

})(this);
`;
}

function main() {
  const fresh = buildEngines();
  if (process.argv.includes('--check')) {
    const current = fs.existsSync(outFile) ? fs.readFileSync(outFile, 'utf8') : '';
    if (current !== fresh) {
      console.error('gas-app/Engines.gs is stale. Run: node tools/build-gas-engines.js');
      process.exit(1);
    }
    console.log('gas-app/Engines.gs is up to date.');
    return;
  }
  fs.writeFileSync(outFile, fresh);
  console.log(`Wrote ${path.relative(root, outFile)}`);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) main();
