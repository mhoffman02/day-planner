// The project handoff skill (.agents/skills/handoff/SKILL.md, the copy agy and this repo's Claude sessions load)
// is generated from the user-level skill plus a day-planner addendum, so the two can never drift apart.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { buildProjectSkill } from '../tools/sync-handoff-skill.js';

const userSkill = '---\nname: handoff\ndescription: Generic handoff.\n---\n\n# handoff\n\nStep 0 ...\n';
const addendum = '## Project addendum (day-planner)\n\n- Archive to TODO_HISTORY.md.\n';

test('keeps the user frontmatter, marks the file generated, points at the addendum, and appends it last', () => {
  const out = buildProjectSkill(userSkill, addendum);
  assert.ok(out.startsWith('---\nname: handoff\ndescription: Generic handoff.\n---\n'), 'frontmatter first');
  assert.match(out, /GENERATED by tools\/sync-handoff-skill\.js/);
  assert.match(out, /Project addendum.*overrides/);
  assert.ok(out.indexOf('# handoff') < out.indexOf('## Project addendum (day-planner)'), 'generic body before addendum');
  assert.ok(out.endsWith('- Archive to TODO_HISTORY.md.\n'));
});

test('fails loud on a user skill without frontmatter', () => {
  assert.throws(() => buildProjectSkill('# no frontmatter', addendum), /frontmatter/);
});
